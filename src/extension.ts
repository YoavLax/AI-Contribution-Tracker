// The module 'vscode' contains the VS Code extensibility API
// Import the module and reference it with the alias vscode in your code below
import * as vscode from 'vscode';
import { CopilotTracker } from './tracker';
import * as fs from 'fs';
import * as path from 'path';
import { execSync } from 'child_process';
import * as os from 'os';

// Create a global output channel
export const logger = vscode.window.createOutputChannel("AI Tracker Debug");

// Minimal Git API definition
interface GitAPI {
    repositories: Repository[];
}
interface Repository {
    rootUri: vscode.Uri;
}
interface GitExtension {
    getAPI(version: number): GitAPI;
}

export function activate(context: vscode.ExtensionContext) {
    logger.appendLine('ACTIVATE: Extension is starting...');
	console.log('ACTIVATE: Extension is starting (console)...');
    
    // Setup global git hooks
    setupGlobalGitHooks(context);
    
    // Setup Copilot agent hooks
    setupCopilotHooks(context);
    
    let tracker: CopilotTracker | undefined;

    try {
        tracker = new CopilotTracker(logger);
        context.subscriptions.push(tracker);
        logger.appendLine('ACTIVATE: Tracker initialized.');
    } catch (e) {
        logger.appendLine(`ERROR: Failed to init tracker: ${e}`);
        console.error(e);
    }

	const disposable = vscode.commands.registerCommand('copilot-insight-tracker.helloWorld', () => {
		vscode.window.showInformationMessage('Copilot Insight Tracker is running.');
        logger.appendLine('COMMAND: Hello World triggered');
    });

	context.subscriptions.push(disposable);
    
    return { tracker };
}

/**
 * Setup global git hooks that work across all repositories
 */
function setupGlobalGitHooks(context: vscode.ExtensionContext): void {
    try {
        // Create a global hooks directory in the extension's global storage
        const globalHooksDir = path.join(context.globalStorageUri.fsPath, 'git-hooks');
        
        if (!fs.existsSync(globalHooksDir)) {
            fs.mkdirSync(globalHooksDir, { recursive: true });
            logger.appendLine(`[Setup] Created global hooks directory: ${globalHooksDir}`);
        }

        const hookFile = path.join(globalHooksDir, 'commit-msg');

        // Create/update the commit-msg hook
        const hookContent = `#!/bin/sh
# Auto-generated by AI Contribution Tracker Extension
# This hook runs globally for all repositories

IMPACT_FLAG=$(git rev-parse --git-path AI_IMPACT_PENDING)
STATE_FILE=$(git rev-parse --git-path ai-tracker-state.json)

if [ -f "$IMPACT_FLAG" ]; then
    MARKER=$(cat "$IMPACT_FLAG")
    if [ -z "$MARKER" ]; then
        MARKER="Impacted by AI"
    fi
    if ! grep -qF "$MARKER" "$1"; then
        echo "" >> "$1"
        echo "$MARKER" >> "$1"
    fi
    rm "$IMPACT_FLAG"
fi

# Clean up accumulated hook state after commit
if [ -f "$STATE_FILE" ]; then
    rm "$STATE_FILE"
fi
`.replace(/\r\n/g, '\n');

        fs.writeFileSync(hookFile, hookContent);
        
        // Make executable on Unix-like systems
        if (os.platform() !== 'win32') {
            fs.chmodSync(hookFile, '755');
        }
        
        logger.appendLine(`[Setup] Created/updated commit-msg hook: ${hookFile}`);

        // Check current git global config
        let currentHooksPath: string = '';
        try {
            currentHooksPath = execSync('git config --global core.hooksPath', { 
                encoding: 'utf8',
                stdio: ['pipe', 'pipe', 'pipe']
            }).trim();
        } catch {
            // Not set, which is fine
        }

        // Set global hooks path if not already set to our directory
        if (currentHooksPath !== globalHooksDir) {
            if (currentHooksPath) {
                logger.appendLine(`[Setup] Existing global hooks path: ${currentHooksPath}`);
                logger.appendLine(`[Setup] Will update to extension hooks path: ${globalHooksDir}`);
            }
            
            execSync(`git config --global core.hooksPath "${globalHooksDir}"`, { 
                encoding: 'utf8',
                stdio: ['pipe', 'pipe', 'pipe']
            });
            
            logger.appendLine(`[Setup] ✓ Set global git hooks path: ${globalHooksDir}`);
            logger.appendLine(`[Setup] All repositories will now use AI tracking hooks automatically`);
            
            // Show notification to user
            vscode.window.showInformationMessage(
                'AI Contribution Tracker: Global git hooks configured successfully. All repositories will now track AI contributions.',
                'Show Logs'
            ).then(selection => {
                if (selection === 'Show Logs') {
                    logger.show();
                }
            });
        } else {
            logger.appendLine(`[Setup] Global hooks path already configured: ${globalHooksDir}`);
        }

    } catch (error) {
        logger.appendLine(`[Setup] ERROR setting up global hooks: ${error}`);
        vscode.window.showWarningMessage(
            `AI Contribution Tracker: Failed to setup global git hooks. Manual installation may be required.`,
            'Show Logs'
        ).then(selection => {
            if (selection === 'Show Logs') {
                logger.show();
            }
        });
    }
}

/**
 * Setup Copilot agent hooks globally (~/.copilot/hooks/)
 * These hooks fire during agent sessions to track prompts, agents, and models.
 */
function setupCopilotHooks(context: vscode.ExtensionContext): void {
    try {
        // Copy hook-handler.js to a stable location in global storage
        const hookHandlerDir = path.join(context.globalStorageUri.fsPath, 'copilot-hooks');
        if (!fs.existsSync(hookHandlerDir)) {
            fs.mkdirSync(hookHandlerDir, { recursive: true });
        }

        const bundledHandler = path.join(context.extensionPath, 'dist', 'hook-handler.js');
        const installedHandler = path.join(hookHandlerDir, 'hook-handler.js');

        if (fs.existsSync(bundledHandler)) {
            fs.copyFileSync(bundledHandler, installedHandler);
            logger.appendLine(`[Setup] Copied hook-handler.js to: ${installedHandler}`);
        } else {
            logger.appendLine(`[Setup] WARNING: hook-handler.js not found at: ${bundledHandler}`);
            return;
        }

        // Create hook config pointing to the installed handler
        const userHome = os.homedir();
        const copilotHooksDir = path.join(userHome, '.copilot', 'hooks');
        if (!fs.existsSync(copilotHooksDir)) {
            fs.mkdirSync(copilotHooksDir, { recursive: true });
        }

        // Build the command string
        // Note: process.execPath is the Electron binary, not Node.js.
        // Use 'node' from PATH which is available on developer machines.
        const handlerPathPosix = installedHandler.replace(/\\/g, '/');
        const defaultCommand = `node "${handlerPathPosix}"`;
        const windowsCommand = `node "${installedHandler}"`;

        const hookConfig = {
            hooks: {
                SessionStart: [{
                    type: 'command',
                    command: defaultCommand,
                    windows: windowsCommand,
                    timeout: 10
                }],
                UserPromptSubmit: [{
                    type: 'command',
                    command: defaultCommand,
                    windows: windowsCommand,
                    timeout: 10
                }],
                SubagentStart: [{
                    type: 'command',
                    command: defaultCommand,
                    windows: windowsCommand,
                    timeout: 10
                }],
                SubagentStop: [{
                    type: 'command',
                    command: defaultCommand,
                    windows: windowsCommand,
                    timeout: 10
                }],
                Stop: [{
                    type: 'command',
                    command: defaultCommand,
                    windows: windowsCommand,
                    timeout: 15
                }]
            }
        };

        const configPath = path.join(copilotHooksDir, 'ai-commit-tracker.json');
        fs.writeFileSync(configPath, JSON.stringify(hookConfig, null, 2));
        logger.appendLine(`[Setup] ✓ Copilot hooks config written: ${configPath}`);
        logger.appendLine(`[Setup] Tracking events: SessionStart, UserPromptSubmit, SubagentStart, SubagentStop, Stop`);

    } catch (error) {
        logger.appendLine(`[Setup] ERROR setting up Copilot hooks: ${error}`);
    }
}

